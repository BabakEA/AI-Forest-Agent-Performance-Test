def _write_new(path: Path, body: str, force: bool = False) -> bool:
    if path.exists() and not force:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")
    return True


def _init(dest: Path, force: bool = False) -> None:
    dest = dest.expanduser().resolve()
    dest.mkdir(parents=True, exist_ok=True)
    # Do not reset existing credentials even when --force is passed.
    example = "# AI Forest AFPerf — example secrets; never commit a filled-in .env\nLLM_GATEWAY_TOKEN=\nCIPHER_API_TOKEN=\n"
    examples = resources.files("agent_perf").joinpath("templates", "examples")
    forecast_text = examples.joinpath("ai_forest_03_capacity_forecast.json").read_text(encoding="utf-8")
    names = {
        "benchmark.json": json.dumps(default_suite(), indent=2) + "\n",
        "forecast.json": forecast_text,
        ".env.example": example,
        ".gitignore": ".env\n.env.*\n!.env.example\nresults/\n__pycache__/\n.pytest_cache/\n*.key\n*.pem\n",
        "README.md": f"# AI Forest AFPerf project\n\nGenerated by AFPerf {VERSION}.\n\n"
                     "`afperf start` — visual editor. `afperf performance benchmark.json` — mock benchmark. "
                     "`afperf forecast forecast.json` — capacity model. `afperf docker` — offline Docker scaffold.\n\n"
                     "Credentials: copy `.env.example` to `.env` and enter real keys locally. Do not commit `.env`.\n"
    }
    for name, data in names.items():
        changed = _write_new(dest / name, data, force=force)
        print(f"{'created' if changed else 'kept'} {dest / name}")
    (dest / "results").mkdir(exist_ok=True)
    exdest = dest / "examples"
    exdest.mkdir(exist_ok=True)
    for item in examples.iterdir():
        if item.name.endswith(".json"):
            _write_new(exdest / item.name, item.read_text(encoding="utf-8"), force=force)
    print("Next: cd", dest)
    print("Run: afperf start   |   afperf performance benchmark.json   |   afperf forecast forecast.json")


def _load_json(path: Path) -> dict:
    if not path.is_file():
        raise FileNotFoundError(f"Configuration not found: {path}. Run `afperf init` first.")
    return json.loads(path.read_text(encoding="utf-8"))


def _run_benchmark(config: Path, out: Path, ack_live: bool) -> None:
    cfg = _load_json(config)
    suite = Suite.from_dict(cfg)
    if ack_live:
        suite.ack_live = True
    suite.validate()
    observations, rows = asyncio.run(run_suite(suite))
    save_benchmark(out, observations, rows, suite)
    print(f"Benchmark complete: {out / 'REPORT.md'}")
    print(f"Interactive report: {out / 'dashboard.html'}")
    print(f"Requests CSV: {out / 'requests.csv'}")
    for row in rows:
        print(row)


def _run_forecast(config: Path, out: Path) -> None:
    cfg = _load_json(config)
    if "cases" in cfg:
        sibling = config.with_name("forecast.json")
        if not sibling.is_file():
            raise ValueError(f"{config.name} is a benchmark suite. Forecast requires a capacity JSON (e.g. forecast.json).")
        print(f"{config.name} is a benchmark suite. Using adjacent {sibling.name} for capacity assumptions.")
        cfg = _load_json(sibling)
    results = write_capacity_report(CapacityInputs.from_dict(cfg), out)
    print(f"Forecast report: {out / 'CAPACITY_REPORT.md'}")
    print(f"Planning estimates (NOT measured capacity): {results['workflows_tps_peak']} workflow TPS, {results['total_replicas']} application pods")


def _start(host: str, port: int, headless: bool) -> int:
    path = Path(__file__).resolve().parent / "ui" / "dashboard.py"
    command = [sys.executable, "-m", "streamlit", "run", str(path),
               "--server.address", host, "--server.port", str(port),
               "--server.headless", str(headless).lower()]
    print(f"Starting AFPerf dashboard at http://{host}:{port}/ (Ctrl+C to stop)", flush=True)
    try:
        return subprocess.call(command)
    except KeyboardInterrupt:
        return 130


def _docker(dest: Path, port: int, force: bool) -> None:
    """Bundle an actually buildable local src/ package. No pip/PyPI publishing required.

    Source is copied from installed package into Docker context. Secrets are never copied.
    """
    dest = dest.expanduser().resolve()
    project = dest.parent
    benchmark = project / "benchmark.json"
    forecast = project / "forecast.json"
    if not benchmark.is_file() or not forecast.is_file():
        raise FileNotFoundError("Run `afperf init` in the project directory before `afperf docker`.")
    if dest.exists() and any(dest.iterdir()) and not force:
        raise FileExistsError(f"{dest} already exists and is not empty. Re-run with --force to refresh the generated Docker scaffold.")
    dest.mkdir(parents=True, exist_ok=True)
    source = dest / "src"
    if source.exists(): shutil.rmtree(source)
    (source / "agent_perf").mkdir(parents=True)
    installed = Path(__file__).resolve().parent
    shutil.copytree(installed, source / "agent_perf", dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".env", ".env.*"))
    (source / "pyproject.toml").write_text("""[build-system]
requires = ["setuptools>=65", "wheel"]
build-backend = "setuptools.build_meta"

[project]
name = "afperf"
version = "__AFPERF_VERSION__"
requires-python = ">=3.10"
dependencies = ["httpx>=0.27", "matplotlib>=3.8", "PyYAML>=6.0", "plotly>=5.0", "python-dotenv>=1.0"]

[project.optional-dependencies]
dashboard = ["streamlit>=1.40"]

[project.scripts]
afperf = "agent_perf.afperf_cli:main"
aiforest-perf = "agent_perf.afperf_cli:main"
agent-performance-test = "agent_perf.afperf_cli:main"

[tool.setuptools.packages.find]
include = ["agent_perf*"]

[tool.setuptools.package-data]
agent_perf = ["ui/*.py", "templates/examples/*.json", "templates/*.md"]
""".replace("__AFPERF_VERSION__", VERSION),encoding="utf-8")
    (source / "README.md").write_text("Offline-generated AFPerf application source for Docker. No keys included.\n")
    cfg=dest / "config"
    cfg.mkdir(exist_ok=True)
    # Never embed original user-defined headers/credentials in a Docker image.
    raw_bench = _load_json(benchmark)
    clean_bench = make_benchmark_config(raw_bench,raw_bench.get("cases", []))
    (cfg / "benchmark.json").write_text(json.dumps(clean_bench, indent=2) + "\n",encoding="utf-8")
    (cfg / "forecast.json").write_text(forecast.read_text(encoding="utf-8"), encoding="utf-8")
    (cfg/"examples").mkdir(exist_ok=True)
    # Only trusted shipped presets; arbitrary user examples may contain sensitive payloads.
    for item in resources.files("agent_perf").joinpath("templates", "examples").iterdir():
        if not item.name.endswith(".json"):
            continue
        contents = json.loads(item.read_text(encoding="utf-8"))
        if isinstance(contents,dict) and "cases" in contents:
            contents = make_benchmark_config(contents, contents.get("cases", []))
        (cfg/"examples"/item.name).write_text(json.dumps(contents,indent=2) + "\n",encoding="utf-8")
    dockerfile = """FROM python:3.12-slim
ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 MPLBACKEND=Agg
WORKDIR /opt/afperf
COPY src/ /opt/afperf/
RUN python -m pip install --no-cache-dir ".[dashboard]"
WORKDIR /workspace
COPY config/ /workspace/
EXPOSE 8501
CMD ["afperf", "start", "--host", "0.0.0.0", "--port", "8501", "--headless"]
"""
    compose = f"""services:
  afperf-dashboard:
    build:
      context: .
      dockerfile: Dockerfile
    image: ai-forest/afperf:{VERSION}
    ports:
      - "127.0.0.1:{port}:8501"
    extra_hosts:
      - "host.docker.internal:host-gateway"
    volumes:
      - ../results:/workspace/results
    restart: unless-stopped
    environment:
      PYTHONUNBUFFERED: "1"
"""
    startsh = """#!/usr/bin/env sh
set -eu
cd "$(dirname "$0")"
case "${1:-help}" in
  build) docker build -t ai-forest/afperf:__AFPERF_VERSION__ . ;;
  run) docker run --rm --name ai-forest-afperf -p 127.0.0.1:8501:8501 --add-host=host.docker.internal:host-gateway -v "$(pwd)/../results:/workspace/results" ai-forest/afperf:__AFPERF_VERSION__ ;;
  compose) docker compose up --build -d ;;
  down) docker compose down ;;
  *) printf 'Usage: sh docker/start.sh {build|run|compose|down}\n' ;;
esac
"""
    startsh = startsh.replace("__AFPERF_VERSION__", VERSION).replace("127.0.0.1:8501:8501", f"127.0.0.1:{port}:8501")
    files = {"Dockerfile":dockerfile,"docker-compose.yml":compose,"start.sh":startsh,
             ".dockerignore":"**/__pycache__\n**/*.pyc\n**/.env\n**/.env.*\n**/*.key\n**/*.pem\n**/results\n**/.git\n",
             "README.md":"# AFPerf Docker bundle\n\nGenerated from the locally installed AFPerf source. Run `sh docker/start.sh build`, `run`, `compose`, or `down` from the project root.\n\nDashboard: http://127.0.0.1:8501/\n\nFor gateway on host from Docker, use `host.docker.internal` rather than `127.0.0.1` (which means container itself).\n\nNo `.env` or credentials are baked into the image. For `docker run` supply `--env-file` explicitly if needed; for compose, configure secrets separately. Do not expose this unauthenticated dashboard to the public internet.\n\n`afperf docker` creates files only and does NOT execute Docker.\n"}
    for name,body in files.items():
        (dest/name).write_text(body,encoding="utf-8")
    (dest/"start.sh").chmod(0o755)
    print(f"Generated Docker bundle at {dest}")
    print("Use: sh docker/start.sh build | run | compose | down")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="afperf", description="AI Forest Agent Performance Test — visual configuration, benchmark, capacity forecast, Docker scaffold")
    parser.add_argument("--version", action="version", version=f"AFPerf {VERSION}")
    sub = parser.add_subparsers(dest="command", required=True)
    ini = sub.add_parser("init", help="Create a new AFPerf project with safe JSON templates")
    ini.add_argument("path", nargs="?", default=".")
    ini.add_argument("--force", action="store_true", help="Overwrite generated non-secret templates")
    sta = sub.add_parser("start", help="Run the Streamlit dashboard locally")
    sta.add_argument("--host", default="127.0.0.1")
    sta.add_argument("--port", type=int, default=8501)
    sta.add_argument("--headless", action="store_true")
    for command in ["performance", "benchmark"]:
        s = sub.add_parser(command, help="Run mock tests or explicitly authorized live workloads")
        s.add_argument("config", nargs="?", default="benchmark.json")
        s.add_argument("--config", dest="config_flag", default=None, help="Alternate configuration filename")
        s.add_argument("--out", default="results/benchmark")
        s.add_argument("--ack-live", action="store_true")
    fc = sub.add_parser("forecast", help="Generate Kubernetes capacity planning report")
    fc.add_argument("config", nargs="?", default="forecast.json")
    fc.add_argument("--config", dest="config_flag", default=None)
    fc.add_argument("--out", default="results/forecast")
    dock = sub.add_parser("docker", help="Generate offline Dockerfile, src, compose, start.sh")
    dock.add_argument("--output", default="docker")
    dock.add_argument("--port", type=int, default=8501)
    dock.add_argument("--force", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.command == "init":
            _init(Path(args.path),args.force)
        elif args.command == "start":
            return _start(args.host,args.port,args.headless)
        elif args.command == "docker":
            _docker(Path(args.output),args.port,args.force)
        else:
            load_project_env()
            config = Path(args.config_flag or args.config)
            if args.command in ("benchmark","performance"):
                _run_benchmark(config,Path(args.out),args.ack_live)
            else:
                _run_forecast(config,Path(args.out))
    except (ValueError, OSError, RuntimeError, KeyError) as exc:
        print(f"AFPerf error: {exc}",file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
